// Reverse of a number
// 2973 is a no
// reverse is 3792

// 0->3->30->37->370->379->3790->3792
#include <iostream>
using namespace std;

int main()
{
    int n;
    cout << "Enter the no:";
    cin >> n;
    for (int i = 0; i <= n; i--)
    {
        cout << n << " ";
        break;
    }
}